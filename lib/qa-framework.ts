// 4. สรุปผลการตัดสินภาพรวมระดับมาตรฐาน สมศ.
// -----------------------------------------------------------------------------
export type AssessmentDecision = "เป็นไปตามมาตรฐาน" | "อยู่ระหว่างการพัฒนา" | "รอการประเมิน";

export function evaluateStandardStatus(scores: number[]): AssessmentDecision {
  if (scores.length === 0 || scores.some((s) => s === 0)) return "รอการประเมิน";
  // สมศ.: กรณีที่สถานศึกษามีผลการดำเนินงานแต่ละมาตรฐานครบถ้วนตามตัวชี้วัดที่กำหนด (ระดับ 3 ขึ้นไปทุกตัวชี้วัด) = เป็นไปตามมาตรฐาน
  const allMeetStandard = scores.every((s) => s >= 3);
  return allMeetStandard ? "เป็นไปตามมาตรฐาน" : "อยู่ระหว่างการพัฒนา";
}


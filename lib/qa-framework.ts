// 6. ระบบตรวจสอบและคำนวณความครบถ้วนของหลักฐานอัตโนมัติ (Automated Evidence Audit)
// -----------------------------------------------------------------------------
export interface EvidenceAuditResult {
  code: string;
  title: string;
  standardCode: string;
  attachedCount: number;
  expectedMinCount: number; // เกณฑ์ขั้นต่ำในการยืนยันความน่าเชื่อถือ (อย่างน้อย 2 รายการตามแนวทาง สมศ.)
  completenessPercent: number;
  status: "complete" | "partial" | "missing";
  statusText: string;
  statusColor: string;
  requiredExamples: string[];
  recommendation: string;
}

export function auditIndicatorEvidence(
  ind: QAIndicatorDef,
  attachedCount: number
): EvidenceAuditResult {
  const expectedMinCount = 2; // สมศ. กำหนดให้มีร่องรอยตรวจสอบได้ชัดเจนอย่างน้อย 2 แหล่ง/ประเภทขึ้นไป
  const completenessPercent = Math.min(100, Math.round((attachedCount / expectedMinCount) * 100));

  let status: "complete" | "partial" | "missing" = "missing";
  let statusText = "ยังไม่มีหลักฐาน (เสี่ยงตกเกณฑ์)";
  let statusColor = "#dc2626";
  let recommendation = "ต้องแนบร่องรอยการปฏิบัติงานตามสภาพจริงอย่างน้อย 2 รายการเพื่อรองรับเกณฑ์ระดับ 3";

  if (attachedCount >= expectedMinCount) {
    status = "complete";
    statusText = "หลักฐานครบถ้วนตามเกณฑ์";
    statusColor = "#16a34a";
    recommendation = "หลักฐานเชิงประจักษ์เพียงพอสำหรับยืนยันผลการดำเนินงานระดับ 3 ขึ้นไป";
  } else if (attachedCount > 0) {
    status = "partial";
    statusText = "มีหลักฐานบางส่วน (ยังไม่สมบูรณ์)";
    statusColor = "#ea580c";
    recommendation = "ควรเพิ่มหลักฐานสนับสนุนอีกอย่างน้อย 1 รายการเพื่อความน่าเชื่อถือในการประเมิน";
  }

  return {
    code: ind.code,
    title: ind.title,
    standardCode: ind.standardCode,
    attachedCount,
    expectedMinCount,
    completenessPercent,
    status,
    statusText,
    statusColor,
    requiredExamples: ind.evidenceExamples,
    recommendation,
  };
}
